// Нормалізація найменування ПТО для порівняння: у наказі одна й та сама
// позиція трапляється то з апострофом ’, то з ', через тире різної довжини,
// з іншим регістром чи подвійними пробілами. Пробіли прибираються повністю —
// при переносі слова між рядками таблиці вони зникають або з'являються.
// Один нормалізатор на весь проєкт: розбіжні копії вже давали дублікати.
export const normalizeName = (s) => String(s ?? '')
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/[‒–—]/g, '-')
    .replace(/[^\wа-яіїєґ']+/gi, '')

export default normalizeName
