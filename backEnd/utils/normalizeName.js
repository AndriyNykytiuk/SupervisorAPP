// Нормалізація найменування ПТО для порівняння між нормами різних типів
// техніки: у наказі одна й та сама позиція трапляється то з апострофом ’,
// то з ', то через тире різної довжини, з іншим регістром чи подвійними
// пробілами. Один нормалізатор на весь проєкт — розбіжні копії вже давали
// дублікати в довіднику.
export const normalizeName = (s) => String(s ?? '')
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/[‒–—]/g, '-')
    .replace(/[^\wа-яіїєґ']+/gi, ' ')
    .trim()
    .replace(/\s+/g, ' ')

export default normalizeName
